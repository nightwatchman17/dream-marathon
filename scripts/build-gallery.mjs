// Rebuilds gallery/photos.js from the files inside gallery/.
// Existing captions are kept, so you only write a caption once.
//
// Usage: node scripts/build-gallery.mjs

import { readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const galleryDir = path.join(root, "gallery");
const manifestPath = path.join(galleryDir, "photos.js");
const imageExtensions = new Set([".jpg", ".jpeg", ".png", ".webp", ".avif", ".gif"]);

const prettify = (fileName) => {
  const words = fileName
    .replace(/\.[^.]+$/, "")
    .replace(/[-_]+/g, " ")
    .replace(/\s+/g, " ")
    .trim()
    .replace(/\b\w/g, (character) => character.toUpperCase());
  return words || "Dream Marathon Spirit";
};

const readPreviousCaptions = async () => {
  try {
    const text = await readFile(manifestPath, "utf8");
    const match = text.match(/=\s*(\[[\s\S]*\])\s*;?/);
    if (!match) return new Map();
    const entries = JSON.parse(match[1]);
    return new Map(
      entries
        .filter((entry) => entry && typeof entry.src === "string")
        .map((entry) => [path.basename(entry.src), entry.caption])
    );
  } catch {
    return new Map();
  }
};

const captions = await readPreviousCaptions();

const files = (await readdir(galleryDir, { withFileTypes: true }))
  .filter((entry) => entry.isFile() && imageExtensions.has(path.extname(entry.name).toLowerCase()))
  .map((entry) => entry.name)
  .sort((a, b) => a.localeCompare(b, undefined, { numeric: true, sensitivity: "base" }));

const photos = files.map((fileName) => ({
  src: `gallery/${fileName}`,
  caption: captions.get(fileName) || prettify(fileName),
}));

const output = `// Gallery photo manifest — generated by scripts/build-gallery.mjs
// Add photos to the gallery/ folder, then run: node scripts/build-gallery.mjs
// Each entry looks like: { "src": "gallery/photo-file.jpg", "caption": "Short description" }
window.DREAM_MARATHON_GALLERY = ${JSON.stringify(photos, null, 2)};
`;

await writeFile(manifestPath, output, "utf8");
console.log(`Gallery manifest updated: ${photos.length} photo(s) from gallery/.`);
